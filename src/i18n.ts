import * as SecureStore from "./data/secureStore";

export type Language = "fr" | "en" | "ln" | "sw";

function readLanguage(): Language {
  try {
    const value = SecureStore.getItem("commerce.language");
    return value === "en" || value === "ln" || value === "sw" ? value : "fr";
  } catch {
    return "fr";
  }
}

export let activeLanguage: Language = readLanguage();

export function setActiveLanguage(language: Language): void {
  activeLanguage = language;
  try {
    SecureStore.setItem("commerce.language", language);
  } catch {
    // Le stockage local reste optionnel.
  }
}

