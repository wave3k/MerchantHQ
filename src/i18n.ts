type RuleMap = {
  hello: string;
  disp: string;
  result: string;
  article: string;
  vente: string;
  stock: string;
  stockbas: string;
  ajoute: string;
};

const rules: Record<Exclude<Language, "fr">, RuleMap> = {
  en: { hello: "Hello, ", disp: " available", result: " result(s)", article: " item(s)", vente: " sale(s)", stock: " in stock", stockbas: "Low stock · ", ajoute: "Added " },
  ln: { hello: "Mbote, ", disp: " ezali", result: " résultat", article: " biloko", vente: " vente", stock: " na stock", stockbas: "Stock ekiti · ", ajoute: "Bakisami le " },
  sw: { hello: "Habari, ", disp: " zinapatikana", result: " matokeo", article: " bidhaa", vente: " mauzo", stock: " katika akiba", stockbas: "Akiba ndogo · ", ajoute: "Imeongezwa " },
};

export function t(value: string): string {
  if (activeLanguage === "fr") return value;
  const dict = activeLanguage === "en" ? english : activeLanguage === "ln" ? lingala : swahili;
  if (dict[value]) return dict[value];
  const r = rules[activeLanguage];
  if (value.startsWith("Bonjour, ")) return value.replace("Bonjour, ", r.hello);
  if (/^\d+ disponible\(s\)$/.test(value)) {
    return value.replace(" disponible(s)", r.disp);
  }
  if (/^\d+ résultat\(s\)$/.test(value)) {
    return value.replace(" résultat(s)", r.result);
  }
  if (/^\d+ article\(s\)$/.test(value)) {
    return value.replace(" article(s)", r.article);
  }
  if (/^\d+ vente\(s\)$/.test(value)) {
    return value.replace(" vente(s)", r.vente);
  }
  if (/^\d+ en stock$/.test(value)) return value.replace(" en stock", r.stock);
  if (value.startsWith("Stock bas · ")) {
    return value.replace("Stock bas · ", r.stockbas);
  }
  if (value.startsWith("Ajouté le ")) return value.replace("Ajouté le ", r.ajoute);
  return value;
}
